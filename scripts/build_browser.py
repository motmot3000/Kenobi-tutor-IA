#!/usr/bin/env python3
"""Generate browser/shared.js from the Python modules.

The web version of Kenobi (no server: everything runs in the browser) reuses the tutor's texts and the
application's constants. They live in the Python modules, which stay the single source of truth: this script
copies them into browser/shared.js. Run it after changing a prompt, a provider or a voice:

    python3 scripts/build_browser.py           # write browser/shared.js
    python3 scripts/build_browser.py --check   # exit 1 if browser/shared.js is out of date
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import courses  # noqa: E402
import memory  # noqa: E402
import providers  # noqa: E402
import settings  # noqa: E402
import speech_text  # noqa: E402
import tutor  # noqa: E402
import voice  # noqa: E402

TARGET = ROOT / "browser" / "shared.js"
HEADER = """// GENERATED by scripts/build_browser.py from the Python modules: do not edit by hand.
// The tutor's texts and the application's constants have one source of truth, the Python code.
"""


def _plain(value):
    """JSON-ready copy: tuples become lists, boolean keys become "true" / "false"."""
    if isinstance(value, dict):
        return {(str(key).lower() if isinstance(key, bool) else str(key)): _plain(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set, frozenset)):
        items = [_plain(item) for item in value]
        return sorted(items) if isinstance(value, (set, frozenset)) else items
    return value


def shared():
    names = {
        "tutor": ("AGENT_NAME", "MAX_MESSAGE", "MAX_REPLY", "MAX_OUTPUT_TOKENS", "VOICE_OUTPUT_TOKENS",
                  "PLAN_EXCERPT_LIMIT", "HISTORY_CHARS", "HISTORY_MESSAGES", "RECENT_MESSAGES", "RECENT_LIMIT",
                  "OLDER_LIMIT", "PERSONA", "PROTOCOL_BASE", "PROTOCOL_CODE", "PROTOCOL_NO_CODE", "VOICE_RULES",
                  "PHONE_RULES", "TERMINAL_STATES", "WATCH_LABELS", "DEFAULT_FILES", "DELIVERY", "QUIZ_EVERY",
                  "CLICK_RULE"),
        "settings": ("PROVIDERS", "REASONING", "VOICE_ENGINES", "LOCAL_VOICES", "MISTRAL_VOICES", "ELEVENLABS_MODEL"),
        "voice": ("MAX_AUDIO", "MAX_SECONDS", "MIN_SECONDS", "MAX_SPOKEN", "FILLER_DELAY_MS", "MISTRAL_API",
                  "MISTRAL_STT_MODEL", "MISTRAL_TTS_MODEL", "ELEVEN_API", "ELEVEN_STT_MODEL", "FILLERS",
                  "GREETINGS_NAMED", "GREETINGS", "TEST_SENTENCE"),
        "courses": ("MAX_DOCUMENT", "MIN_DOCUMENT", "MAX_MODULES", "MAX_LESSONS_PER_MODULE", "MAX_LESSONS",
                    "ANALYSIS_TOKENS", "LANGUAGES", "DEFAULT_FILES", "TEMPLATE", "ANALYSIS_SYSTEM",
                    "AUTHOR_SYSTEM", "AUTHOR_MAX_WISH", "AUTHOR_TOKENS",
                    "_EDITOR_SUFFIXES"),
        "memory": ("LESSON_STATUSES", "FORMER_LESSON_IDS", "PLAN_COURSE_FIELDS", "PLAN_MODULE_FIELDS",
                   "PLAN_LESSON_FIELDS"),
        "providers": ("CONNECT_TIMEOUT", "READ_TIMEOUT", "MAX_LINE", "MAX_REPLY", "ANTHROPIC_VERSION"),
        "speech": ("FIRST_MIN", "FIRST_MAX", "SEGMENT_MAX"),
    }
    modules = {"tutor": tutor, "settings": settings, "voice": voice, "courses": courses, "memory": memory,
               "providers": providers, "speech": speech_text}
    data = {}
    for group, keys in names.items():
        module = modules[group]
        data[group] = {key: _plain(getattr(module, key)) for key in keys if hasattr(module, key)}
    # Course vocabulary given to the speech recognition during a call (server.py), kept here to avoid importing the
    # HTTP server.
    data["voiceTerms"] = _plain(_voice_terms())
    return data


def _voice_terms():
    source = (ROOT / "server.py").read_text(encoding="utf-8")
    start = source.index("VOICE_TERMS = {")
    end = source.index("\n}\n", start) + 2
    scope = {}
    exec(source[start:end], scope)  # a literal dict of tuples, nothing else
    return scope["VOICE_TERMS"]


def render():
    body = json.dumps(shared(), ensure_ascii=False, indent=1, sort_keys=True)
    return (HEADER + "(function (root, factory) {\n"
            "  const api = factory();\n"
            "  if (typeof module === \"object\" && module.exports) module.exports = api;\n"
            "  root.KenobiShared = api;\n"
            "})(typeof globalThis !== \"undefined\" ? globalThis : this, function () {\n"
            "  \"use strict\";\n"
            f"  return Object.freeze({body});\n"
            "});\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if browser/shared.js is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("browser/shared.js is out of date: run python3 scripts/build_browser.py", file=sys.stderr)
            return 1
        print("browser/shared.js is up to date")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
